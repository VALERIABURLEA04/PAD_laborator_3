const books = db.getSiblingDB(process.env.SEED_DATABASE || "bookcatalog").books;
const count = Math.max(3, parseInt(process.env.SEED_COUNT || "300", 10));

const classics = [
  { Title: "The Hobbit", Author: "J. R. R. Tolkien", PublishedYear: 1937,
    Description: "A fantasy adventure through Middle-earth.", Tags: ["fantasy", "adventure"] },
  { Title: "Dune", Author: "Frank Herbert", PublishedYear: 1965,
    Description: "A science fiction story set on Arrakis.", Tags: ["science fiction"] },
  { Title: "1984", Author: "George Orwell", PublishedYear: 1949,
    Description: "A dystopian novel about surveillance and control.", Tags: ["dystopia", "classic"] }
];

const authors = [
  "Mihai Eminescu", "Ion Creangă", "Liviu Rebreanu", "Mihail Sadoveanu", "Camil Petrescu",
  "Isaac Asimov", "Ursula K. Le Guin", "Agatha Christie", "Jane Austen", "Fyodor Dostoevsky",
  "Leo Tolstoy", "Gabriel García Márquez", "Haruki Murakami", "Umberto Eco", "Terry Pratchett"
];
const adjectives = ["Silent", "Lost", "Golden", "Hidden", "Last", "Broken", "Eternal", "Northern", "Forgotten", "Distant"];
const nouns = ["Kingdom", "River", "Library", "Garden", "Empire", "Voyage", "Archive", "Forest", "Signal", "Harbor"];
const tags = ["fantasy", "classic", "science fiction", "mystery", "romance", "history", "drama", "adventure", "poetry", "dystopia"];

function seedId(index) {
  return ObjectId("671000000000000000" + index.toString(16).padStart(6, "0"));
}

function generated(index) {
  const adjective = adjectives[index % adjectives.length];
  const noun = nouns[Math.floor(index / adjectives.length) % nouns.length];
  return {
    Title: `The ${adjective} ${noun} #${index}`,
    Author: authors[index % authors.length],
    PublishedYear: 1850 + (index * 7) % 175,
    Description: `Demo book ${index} generated by the seed script.`,
    Tags: [tags[index % tags.length], tags[(index * 3 + 1) % tags.length]]
  };
}

const operations = [];
for (let i = 1; i <= count; i++) {
  const details = i <= classics.length ? classics[i - 1] : generated(i);
  operations.push({
    updateOne: {
      filter: { _id: seedId(i) },
      update: { $setOnInsert: details },
      upsert: true
    }
  });
}

const result = books.bulkWrite(operations, { ordered: false });
print(`Seed complete. Inserted ${result.upsertedCount}, already present ${count - result.upsertedCount}.`);
print(`Active books in collection: ${books.countDocuments({ IsDeleted: { $ne: true } })}`);
